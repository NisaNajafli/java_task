package m4hw9;

public class Kalkulyator {
    // İki tam ədəd üçün
    public int vur(int eded1, int eded2) {
        return eded1 * eded2;
    }

    // Üç tam ədəd üçün
    public int vur(int eded1, int eded2, int eded3) {
        return eded1 * eded2 * eded3;
    }

    // İki kəsr ədəd üçün
    public double vur(double eded1, double eded2) {
        return eded1 * eded2;
    }
}
